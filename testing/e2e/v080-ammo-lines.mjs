const W = process.env.TL_WORK || "/tmp/tl-test";
import { chromium } from "playwright";
import { createRequire } from "module";
const req = createRequire(import.meta.url);
const D = req("../../node_modules/better-sqlite3-multiple-ciphers");
const base = "http://127.0.0.1:3100";
const DIR = process.argv[2];
const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/opt/pw-browsers/chromium" });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
let fails = 0; const ok = (c, m) => { if (!c) fails++; console.log(c ? "PASS" : "FAIL", m); };
p.on("pageerror", e => { fails++; console.log("PAGEERROR", e.message); });
const q = (sql, ...a) => { const d = new D(DIR + "/firearms.db", { readonly: true }); try { return d.prepare(sql).get(...a); } finally { d.close(); } };
await p.goto(base + "/ammo");
const ln = p.locator(`[data-caliber="9mm"] [data-line="FMJ · 115gr"]`);
await ln.locator("summary").click();
const bl = ln.locator("[data-brand=Blazer]");
await bl.getByRole("button", { name: "Correct count" }).click();
await ln.locator("input[type=number]").fill("480");
await ln.getByRole("button", { name: "Save correction" }).click(); await p.waitForTimeout(1500);
ok(q("select on_hand from ammo_stock where caliber='9mm' and manufacturer='Blazer' and grain=115").on_hand === 480, "brand line corrected to 480");
const adj = q("select * from count_adjustments order by created_at desc limit 1");
ok(adj.manufacturer === "Blazer" && adj.ammo_type === "FMJ" && adj.grain === 115 && adj.delta === -20, "correction stored on the brand line");
await p.reload();
ok((await p.locator("#corrections > summary").innerText()).includes("2"), "corrections list count");
const before9 = q("select on_hand from ammo_on_hand where caliber='9mm'").on_hand;
await p.goto(base + "/controls#controls-ammo-counts"); await p.waitForTimeout(500);
await p.locator("#controls-ammo-counts").getByRole("button", { name: "Fill all with 0" }).click();
await p.locator("#controls-ammo-counts").getByPlaceholder("Type RESET to confirm").fill("RESET");
await p.locator("#controls-ammo-counts").getByRole("button", { name: /^Apply \d+ change/ }).click(); await p.waitForTimeout(2500);
ok(q("select on_hand from ammo_on_hand where caliber='9mm'").on_hand === 0 && before9 !== 0, "bulk reset 9mm to 0");
ok(q("select count(*) n from ammo_stock where caliber='9mm' and on_hand != 0").n === 0, "every 9mm line zeroed");
await p.goto(base + "/ammo");
ok((await p.locator("[data-goal='9mm']").innerText()).includes("0 / 2,000"), "goal reflects reset");
console.log(fails ? `${fails} FAILED` : "ALL PASS");
await b.close();
